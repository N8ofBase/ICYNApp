import pathlib
root = pathlib.Path(__file__).resolve().parents[2]
def patch(rel, pairs):
    p = root / rel; s = p.read_text(encoding='utf-8'); crlf = b'\r\n' in p.read_bytes()
    for a, b, *n in pairs:
        n = n[0] if n else 1
        if b in s: continue
        assert s.count(a) == n, f'{rel}: expected {n} of {a[:90]!r}, found {s.count(a)}'
        s = s.replace(a, b)
    p.write_text(s, encoding='utf-8', newline='\r\n' if crlf else '\n'); print('patched', rel)


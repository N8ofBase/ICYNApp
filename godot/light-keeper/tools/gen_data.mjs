// Builds scripts/art_data.gd and scripts/rules_data.gd from the HTML prototype's own data and drawing code,
// so the Godot version keeps the exact classic art and ability tables.
// Source: tools/critquest/farluck-battle.html (the lines are pulled into src_extract.js by the README steps).
// Run from this folder: node tools/gen_data.mjs
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';

const here = path.dirname(new URL(import.meta.url).pathname);
const src = fs.readFileSync(path.join(here, 'src_extract.js'), 'utf8');
const ctx = {};
vm.createContext(ctx);
vm.runInContext(src + '\n;globalThis.__x = { LIFEFORMS, ROLES, STATN, TIER_CD, FAMS, COMBOS, SKIN, ROLE_LOOK, ROLE_FRAME, heroSVG, gremlinArt, actIcon, cornerSVG, dieSVG, DICE_LOOK };', ctx);
const X = ctx.__x;

// ThorVG (Godot's SVG rasterizer) is happiest with plain hex colors and no <text>.
function clean(s) {
  s = s.replace(/(fill|stroke)="rgba\(\s*([\d.]+)\s*,\s*([\d.]+)\s*,\s*([\d.]+)\s*,\s*([\d.]+)\s*\)"/g, (m, k, r, g, b, a) => {
    const hx = '#' + [r, g, b].map(v => (+v).toString(16).padStart(2, '0')).join('');
    return `${k}="${hx}" ${k}-opacity="${a}"`;
  });
  s = s.replace(/<text[^>]*>[^<]*<\/text>/g, '');
  return s.replace(/\s+/g, ' ').trim();
}
const wrap = (vb, body) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${vb}">${body}</svg>`;
const OUT = {};

// Heroes: every Lifeform in every Role, facing right, feet at (0,0).
const SIZE = lf => lf === 'Melkin' ? 0.62 : lf === 'Dimoneesh' ? 0.9 : 1;
for (const lf of Object.keys(X.LIFEFORMS)) for (const role of Object.keys(X.ROLES)) {
  const L = { lf, role, skin: X.SKIN[lf], cloak: X.ROLE_LOOK[role], size: SIZE(lf) };
  OUT[`hero/${lf}/${role}`] = clean(wrap('-60 -130 120 140', X.heroSVG(L)));
}
OUT['gremlin'] = clean(wrap('-30 -40 60 46', X.gremlinArt(0, 0)));

// Action icons (32x32): the basic actions, the weapon attack per weapon, and one per ability.
const ic = (k, s) => OUT['icon/' + k] = clean(s.replace('<svg viewBox="0 0 32 32" aria-hidden="true">', '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32">'));
for (const k of ['move', 'defend', 'end']) ic(k, X.actIcon(k, {}));
for (const w of ['Fists', 'Blade', 'Stringbow', 'Staff spark', 'Daggers', 'Claws']) ic('attack/' + w, X.actIcon('attack', { weapon: w }));
for (const F of X.FAMS) for (const a of F.versions) ic('ab/' + a.name, X.actIcon('ab0', { abs: [a] }));

// Battle bar icons (from the HTML bar), the help "?" drawn as a path because ThorVG has no fonts.
const B = {
  roster: '<path d="M16 3 L27 7 V15 Q27 24 16 29 Q5 24 5 15 V7Z" fill="#7a2e1c" stroke="#e8c260" stroke-width="2"/><path d="M11 15 l4 4 l7 -8" stroke="#e8c260" stroke-width="2.5" fill="none"/>',
  log: '<rect x="7" y="5" width="18" height="22" rx="2" fill="#e6d3a8" stroke="#8a6a3a" stroke-width="2"/><path d="M11 11h10M11 15h10M11 19h7" stroke="#5a4630" stroke-width="1.8"/><circle cx="7" cy="7" r="3" fill="#c99a3c"/><circle cx="7" cy="25" r="3" fill="#c99a3c"/>',
  key: '<polygon points="16,4 27,10 27,22 16,28 5,22 5,10" fill="#8aa04a" stroke="#e8c260" stroke-width="2"/><circle cx="16" cy="14" r="5" fill="#3f6b2f"/><rect x="15" y="18" width="2" height="5" fill="#5b4026"/>',
  pace: '<path d="M9 4h14M9 28h14M10 4 Q10 13 16 16 Q10 19 10 28 M22 4 Q22 13 16 16 Q22 19 22 28" stroke="#e8c260" stroke-width="2" fill="none"/><path d="M12 25 Q16 20 20 25Z" fill="#c99a3c"/>',
  help: '<circle cx="16" cy="16" r="12" fill="#3a2e24" stroke="#e8c260" stroke-width="2"/><path d="M12 12.5 Q12 8.5 16 8.5 Q20 8.5 20 12 Q20 14.5 17 15.5 Q16 16 16 18.5" stroke="#f3e6c8" stroke-width="2.4" fill="none" stroke-linecap="round"/><circle cx="16" cy="22.5" r="1.6" fill="#f3e6c8"/>',
};
for (const k in B) OUT['bar/' + k] = clean(wrap('0 0 32 32', B[k]));

// Role corner ornaments for the full-screen frame.
for (const role of Object.keys(X.ROLES)) OUT['corner/' + role] = clean(X.cornerSVG(role).replace('<svg viewBox', '<svg xmlns="http://www.w3.org/2000/svg" viewBox'));

// Crit Dice bodies (numbers are drawn by Godot on top). d6 faces carry their pips.
for (const team of ['A', 'B']) {
  const look = X.DICE_LOOK[team];
  for (const s of [4, 8, 10, 12, 20]) OUT[`die/${team}/${s}`] = clean(X.dieSVG(s, '', look).replace('<svg viewBox', '<svg xmlns="http://www.w3.org/2000/svg" viewBox'));
  for (let v = 1; v <= 6; v++) OUT[`die/${team}/6/${v}`] = clean(X.dieSVG(6, v, look).replace('<svg viewBox', '<svg xmlns="http://www.w3.org/2000/svg" viewBox'));
}

const gdStr = s => '"' + s.replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '"';
let art = '# Generated by tools/gen_data.mjs from the HTML prototype. Do not edit by hand.\nextends RefCounted\n\nconst SVG := {\n';
for (const k of Object.keys(OUT)) art += `\t${gdStr(k)}: ${gdStr(OUT[k])},\n`;
art += '}\n';
fs.writeFileSync(path.join(here, '..', 'scripts', 'art_data.gd'), art);

// Rules tables. JSON is valid GDScript literal syntax.
const abilities = [];
for (const F of X.FAMS) for (const a of F.versions) abilities.push(a);
const J = o => JSON.stringify(o, null, '\t').replace(/\n/g, '\n');
let rules = '# Generated by tools/gen_data.mjs from the HTML prototype (abilities N8 picked on Nov 11). Do not edit by hand.\nextends RefCounted\n\n';
rules += `const LIFEFORMS := ${J(X.LIFEFORMS)}\n\nconst ROLES := ${J(X.ROLES)}\n\nconst STATN := ${J(X.STATN)}\n\nconst TIER_CD := { 1: 1, 3: 2 }\n\n`;
rules += `const SKIN := ${J(X.SKIN)}\n\nconst ROLE_FRAME := ${J(X.ROLE_FRAME)}\n\nconst ABILITIES := ${J(abilities)}\n`;
fs.writeFileSync(path.join(here, '..', 'scripts', 'rules_data.gd'), rules);
console.log(Object.keys(OUT).length, 'svgs;', abilities.length, 'abilities');
